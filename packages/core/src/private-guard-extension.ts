import * as path from "node:path";
import { writeLineageArtifact } from "./lineage-artifact";
import { generatedRootBindingSource } from "./generated-extension-source";

/**
 * A private session (issue #852) writes nothing into the memory system. The
 * two *passive* channels close through the omp-ui-private.yml overlay; the
 * four *active* ones are plain model tools with no `<tool>.enabled` config
 * key (probed against the omp binary: the full key list contains none of
 * them), so the only per-session way to close them is the runtime apply path
 * the plan bridge already uses for its read-only toggle: read the live
 * roster, hand omp the roster minus the write tools through
 * `setActiveToolPresentation` (else `setActiveToolsByName`).
 *
 * Delivered as a generated `-e` bridge beside the transcript, the same shape
 * as the knowledge-vault bridge: it registers the hidden command
 * `/omp-ui-private`, and the spawner pushes it through initialCommands when
 * — and only when — the session record says private. Recall and reflect stay
 * mounted: the guard removes exactly the four write tools. A session whose
 * omp exposes no apply path arms nothing and says so once; the overlay layer
 * still holds, so the arm failure is never fatal.
 */

export const PRIVATE_GUARD_COMMAND = "omp-ui-private";
/** The extension file lives beside the transcript so it dies with the lineage. */
const EXTENSION_NAME = "omp-ui-private-guard.ts";

/** omp's memory-system tools that persist session content; names mirror the
 *  binary's registry (and ./watchdog's known-tool list). */
export const PRIVATE_DISABLED_TOOLS = ["memory_edit", "retain", "learn", "manage_skill"] as const;

export function privateGuardExtensionPath(lineageDir: string): string {
  return path.join(lineageDir, EXTENSION_NAME);
}

/** Rewritten on every spawn, like every generated bridge. */
export function writePrivateGuardExtension(lineageDir: string): string {
  return writeLineageArtifact(
    lineageDir,
    privateGuardExtensionPath(lineageDir),
    extensionSource(),
  );
}

/** The hidden slash command the spawner pushes through initialCommands. */
export function privateGuardArmMessage(): string {
  return `/${PRIVATE_GUARD_COMMAND}`;
}

/**
 * The generated source imports nothing; the command name and tool list are
 * interpolated from this module so the two sides can never drift.
 */
function extensionSource(): string {
  return `// Generated by omp-ui. Rewritten on every spawn; edits are not preserved.

const COMMAND = ${JSON.stringify(PRIVATE_GUARD_COMMAND)};
const DISABLED = ${JSON.stringify([...PRIVATE_DISABLED_TOOLS])};

/** The slice of omp's AgentSession this extension drives. */
interface GuardSession {
  /** Legacy apply path; the presentation setter below is used when present. */
  setActiveToolsByName?: (names: string[]) => Promise<void>;
  /**
   * omp's presentation-aware apply path — the same call the capabilities
   * bridge and the plan bridge apply with. Optional: an omp without it falls
   * back to \`setActiveToolsByName\`.
   */
  setActiveToolPresentation?: (
    enabled: string[],
    mounted: string[],
    forcePromptRefresh?: boolean,
  ) => unknown;
  getEnabledToolNames: () => string[];
  /** Mounted xd:// names; absent on an omp with no xdev surface. */
  getMountedXdevToolNames?: () => unknown;
}

interface GuardUi {
  notify: (message: string, level?: "info" | "warning" | "error") => void;
}

interface GuardExtensionApi {
  pi?: { AgentSession?: { prototype?: Record<string, unknown> } };
  registerCommand: (
    name: string,
    options: {
      description?: string;
      handler: (args: string, ctx: { ui: GuardUi }) => Promise<void>;
    },
  ) => void;
}

export default function (pi: GuardExtensionApi) {
  // The first prompting AgentSession. omp dispatches slash commands through
  // prompt, so the arming command itself binds the root; no later prompt —
  // descendant or not — may retarget it (ADR-0008 discipline).
  let rootSession: GuardSession | null = null;
  let warnedUnsupported = false;
  ${generatedRootBindingSource("GuardSession")}

  try {
    const prototype = pi.pi?.AgentSession?.prototype;
    const originalPrompt = prototype?.prompt;
    if (prototype && typeof originalPrompt === "function") {
      const call = originalPrompt as (this: GuardSession, ...a: unknown[]) => unknown;
      prototype.prompt = function (this: GuardSession, ...args: unknown[]): unknown {
        captureRoot(this);
        return call.apply(this, args);
      };
    }
  } catch {
    // Without the hook there is no root to arm; the handler warns once.
  }

  /**
   * The enabled roster as of right now. A roster that is not an array is an
   * error, never an empty list: guessing one would drop every other tool.
   */
  function readEnabled(active: GuardSession): string[] {
    const names = active.getEnabledToolNames() as unknown;
    if (!Array.isArray(names)) throw new Error("getEnabledToolNames answered with no roster");
    return names.filter(name => typeof name === "string");
  }

  /** Mounted xd:// names; an omp with no xdev surface mounts nothing. */
  function readMounted(active: GuardSession): string[] {
    const read = active.getMountedXdevToolNames;
    if (typeof read !== "function") return [];
    const names = read.call(active) as unknown;
    return Array.isArray(names) ? names.filter(name => typeof name === "string") : [];
  }

  /**
   * Hand the roster to omp: the presentation setter when the runtime has one
   * — the same call the capabilities bridge applies with, which is why the
   * mounted list it gets is the intersection — and the by-name setter on an
   * omp that predates it. Neither existing is the unsupported-omp case the
   * handler reports once.
   */
  async function applyTools(
    active: GuardSession,
    nextEnabled: string[],
    currentMounted: string[],
  ): Promise<void> {
    const present = active.setActiveToolPresentation;
    if (typeof present === "function") {
      const mounted = currentMounted.filter(name => nextEnabled.indexOf(name) >= 0);
      await Promise.resolve(present.call(active, nextEnabled, mounted, true));
      return;
    }
    const byName = active.setActiveToolsByName;
    if (typeof byName !== "function") throw new Error("this omp session can apply no tool roster");
    await byName.call(active, nextEnabled);
  }

  // Two arms must not interleave their roster reads.
  let chain: Promise<void> = Promise.resolve();
  function serialize(work: () => Promise<void>): Promise<void> {
    const next = chain.then(work, work);
    chain = next.then(
      () => undefined,
      () => undefined,
    );
    return next;
  }

  pi.registerCommand(COMMAND, {
    description: "omp-ui private-session memory guard",
    handler: (_args: string, ctx: { ui: GuardUi }) =>
      serialize(async () => {
        const active = rootSession;
        if (!active || typeof active.getEnabledToolNames !== "function") {
          if (!warnedUnsupported) {
            warnedUnsupported = true;
            ctx.ui.notify("omp-ui private guard: this omp exposes no tool roster to quiet", "warning");
          }
          return;
        }
        // A tool absent from the enabled roster is simply skipped: the filter
        // is the whole removal, so an omp that never mounted one arms clean.
        const enabled = readEnabled(active);
        const next = enabled.filter(name => DISABLED.indexOf(name) < 0);
        // Nothing enabled to remove: nothing changed, so nothing is applied —
        // an apply here would refresh the prompt for no reason.
        if (next.length === enabled.length) return;
        try {
          await applyTools(active, next, readMounted(active));
        } catch {
          // No apply path (or a rejected one): one line, never a throw — the
          // config overlay already closed the passive channels.
          if (!warnedUnsupported) {
            warnedUnsupported = true;
            ctx.ui.notify("omp-ui private guard: this omp cannot apply the quiet roster", "warning");
          }
        }
      }),
  });
}
`;
}
