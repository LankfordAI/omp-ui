import * as path from "node:path";
import {
  SIDE_COMMANDS_COMMAND,
  SIDE_COMMANDS_RENDER_ARG_PREFIX,
  SIDE_COMMANDS_STATUS_BYTE_LIMIT,
  SIDE_COMMANDS_STATUS_KEY,
} from "./side-commands";
import { BTW_QUESTION_CHAR_LIMIT } from "./side-questions";
import { writeLineageArtifact } from "./lineage-artifact";
import {
  generatedAsRecordSource,
  generatedRootBindingSource,
  generatedUtf8LengthSource,
} from "./generated-extension-source";

/**
 * omp ≥ 18.13.0 runs a `side: true` file slash command as /btw only in its
 * TUI; over rpc the same line expands into an ordinary prompt that enters the
 * transcript and steers a running turn (issue #955). The side set lives only
 * on the live `AgentSession.slashCommands` list, and the template expansion
 * (argument substitution plus Handlebars) is omp's own. This generated
 * extension patches `AgentSession.prototype.prompt` to bind the first prompt
 * as the root session, publishes the root's side set over `ui.setStatus`,
 * and renders one command on request with omp's `renderFileSlashCommand`,
 * reached through the literal module specifier omp's extension loader maps
 * (ADR-0036). omp-ui then asks the rendered text through native `btw`.
 *
 * The bridge never polls and never throws into the agent: an unreadable list
 * or an unresolvable renderer publishes an `available: false` snapshot.
 */

/** The extension file lives beside the transcript so it dies with the lineage. */
const EXTENSION_NAME = "omp-ui-side-commands.ts";

export function sideCommandsExtensionPath(lineageDir: string): string {
  return path.join(lineageDir, EXTENSION_NAME);
}

/**
 * The extension source is generated per lineage so its wire constants cannot
 * drift from the renderer.
 */
function extensionSource(): string {
  return `// Generated by omp-ui. Rewritten on every spawn; edits are not preserved.
const STATUS_KEY = ${JSON.stringify(SIDE_COMMANDS_STATUS_KEY)};
const COMMAND = ${JSON.stringify(SIDE_COMMANDS_COMMAND)};
const RENDER_ARG_PREFIX = ${JSON.stringify(SIDE_COMMANDS_RENDER_ARG_PREFIX)};
/** Snapshots over this many UTF-8 bytes degrade instead of flooding the status channel. */
const BYTE_LIMIT = ${SIDE_COMMANDS_STATUS_BYTE_LIMIT};
/** omp-ui's cap on one side question; longer renders are refused, never truncated. */
const QUESTION_LIMIT = ${BTW_QUESTION_CHAR_LIMIT};
/** Cap on a renderer error message carried in a snapshot. */
const MESSAGE_LIMIT = 1000;

${generatedAsRecordSource()}

${generatedUtf8LengthSource()}

interface SideSession {
  slashCommands?: unknown;
}

interface StatusUi {
  setStatus: (key: string, text: string | undefined) => void;
}

interface ExtensionApi {
  pi?: { AgentSession?: { prototype?: Record<string, unknown> } };
  registerCommand: (
    name: string,
    options: {
      description?: string;
      handler: (args: string, ctx: { ui: StatusUi }) => Promise<void>;
    },
  ) => void;
}

/** omp's renderFileSlashCommand(command, args): the expanded template text. */
type RenderFn = (command: unknown, args: string) => unknown;

interface RenderRequest {
  requestId: string;
  name: string;
  args: string;
}

type DraftResult =
  | { requestId: string; ok: true; question: string }
  | { requestId: string; ok: false; reason: string; message: string | null };

/**
 * Strict allowlist parse mirroring the client's SideCommandRenderRequest:
 * exact field set, exact types. Malformed payloads return null so the
 * handler throws instead of rendering a guess.
 */
function parseRenderRequest(json: string): RenderRequest | null {
  let value: unknown;
  try {
    value = JSON.parse(json);
  } catch {
    return null;
  }
  const record = asRecord(value);
  if (record === null) return null;
  const keys = Object.keys(record).sort();
  const expected = ["args", "name", "requestId"];
  if (keys.length !== expected.length) return null;
  for (let i = 0; i < expected.length; i++) if (keys[i] !== expected[i]) return null;
  if (typeof record.requestId !== "string") return null;
  if (record.requestId.length === 0 || record.requestId.length > 128) return null;
  if (typeof record.name !== "string" || record.name.length === 0) return null;
  if (typeof record.args !== "string") return null;
  return { requestId: record.requestId, name: record.name, args: record.args };
}

export default function (pi: ExtensionApi) {
  const processKey = "omp-ui-" + Date.now().toString(36) + "-" + Math.random().toString(36).slice(2);
  let rootSession: SideSession | null = null;
  ${generatedRootBindingSource("SideSession")}
  let ui: StatusUi | null = null;
  let revision = 0;
  /** The latest render result, republished with every snapshot until replaced. */
  let result: DraftResult | null = null;

  const renderer: Promise<RenderFn | null> =
    // @ts-expect-error -- literal specifier resolved by omp's extension loader (ADR-0036)
    import("@oh-my-pi/pi-coding-agent/extensibility/slash-commands").then(
      (mod: unknown) => {
        const fn = (mod as Record<string, unknown> | null)?.renderFileSlashCommand;
        return typeof fn === "function" ? (fn as RenderFn) : null;
      },
      () => null,
    );

  /** side: true entries of the live list, or null when unreadable. */
  function sideEntries(): Record<string, unknown>[] | null {
    const root = rootSession;
    if (root === null) return null;
    let list: unknown;
    try {
      list = root.slashCommands;
    } catch {
      return null;
    }
    if (!Array.isArray(list)) return null;
    const entries: Record<string, unknown>[] = [];
    for (const value of list) {
      const entry = asRecord(value);
      if (entry === null) continue;
      if (typeof entry.name !== "string" || entry.name === "") continue;
      if (entry.side !== true) continue;
      entries.push(entry);
    }
    return entries;
  }

  function publish(render: RenderFn | null): void {
    if (ui === null) return;
    const entries = sideEntries();
    const available = render !== null && entries !== null;
    const unavailable = available ? null : rootSession === null ? "no-session" : "missing-api";
    const commands: string[] = [];
    if (available && entries !== null) {
      for (const entry of entries) {
        const name = entry.name as string;
        if (!commands.includes(name)) commands.push(name);
      }
      commands.sort((a, b) => a.localeCompare(b));
    }
    const snapshot = { version: 1, processKey, revision: revision + 1, available, unavailable, commands, result };
    let json = JSON.stringify(snapshot);
    if (utf8Length(json) > BYTE_LIMIT) {
      if (result !== null && result.ok) {
        // The question itself overflowed the channel: refuse it as too long.
        result = { requestId: result.requestId, ok: false, reason: "too-long", message: null };
      }
      json = JSON.stringify({
        ...snapshot,
        available: false,
        unavailable: "payload-too-large",
        commands: [],
        result,
      });
    }
    revision += 1;
    ui.setStatus(STATUS_KEY, json);
  }

  function renderResult(request: RenderRequest, render: RenderFn | null): DraftResult {
    const requestId = request.requestId;
    const entries = sideEntries();
    if (render === null || entries === null) {
      return {
        requestId,
        ok: false,
        reason: "render-failed",
        message: "omp cannot expand slash commands in this session",
      };
    }
    const entry = entries.find((candidate) => candidate.name === request.name);
    if (entry === undefined) return { requestId, ok: false, reason: "not-side", message: null };
    let text: unknown;
    try {
      text = render(entry, request.args);
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      return { requestId, ok: false, reason: "render-failed", message: message.slice(0, MESSAGE_LIMIT) };
    }
    if (typeof text !== "string") {
      return { requestId, ok: false, reason: "render-failed", message: "the command rendered no text" };
    }
    if (text.trim() === "") return { requestId, ok: false, reason: "empty", message: null };
    if (text.length > QUESTION_LIMIT) return { requestId, ok: false, reason: "too-long", message: null };
    return { requestId, ok: true, question: text };
  }

  try {
    const prototype = pi.pi?.AgentSession?.prototype;
    const originalPrompt = prototype?.prompt;
    if (prototype && typeof originalPrompt === "function") {
      const call = originalPrompt as (this: SideSession, ...a: unknown[]) => unknown;
      prototype.prompt = function (this: SideSession, ...args: unknown[]): unknown {
        captureRoot(this);
        return call.apply(this, args);
      };
    }
  } catch {
    /* an unhookable session publishes no-session; it never breaks the agent */
  }

  pi.registerCommand(COMMAND, {
    description: "omp-ui side commands",
    handler: async (args: string, ctx: { ui: StatusUi }) => {
      ui = ctx.ui;
      const render = await renderer;
      const trimmed = typeof args === "string" ? args.trim() : "";
      if (trimmed === "") {
        publish(render);
        return;
      }
      if (!trimmed.startsWith(RENDER_ARG_PREFIX)) throw new Error("omp-ui-side-commands: unsupported command args");
      const request = parseRenderRequest(trimmed.slice(RENDER_ARG_PREFIX.length));
      if (request === null) throw new Error("omp-ui-side-commands: malformed render request");
      result = renderResult(request, render);
      publish(render);
    },
  });
}
`;
}

/**
 * Writes the side-commands extension into the lineage dir and returns its
 * path, to be passed to omp as `-e`. Rewritten on every spawn so a stale copy
 * from an older omp-ui build can never outvote the current wire contract.
 */
export function writeSideCommandsExtension(lineageDir: string): string {
  return writeLineageArtifact(lineageDir, sideCommandsExtensionPath(lineageDir), extensionSource());
}
