import * as fs from "node:fs";
import * as path from "node:path";
import {
  PLAN_COMMAND,
  PLAN_EXECUTE,
  PLAN_REFINE,
  PLAN_REVIEW_SENTINEL,
  PLAN_STATUS_KEY,
} from "./plan";

/**
 * omp's plan mode has no rpc surface (verified against v17.1.8): the
 * `RpcCommand` union carries no plan variant, `get_state` reports no mode,
 * `/plan` defines only `handleTui` so rpc-ui falls through and sends it to the
 * model as literal text, and `plan.defaultOnStartup` is read by
 * `InteractiveMode`/`print-mode` only. `--plan-yolo` does arm in rpc-ui, but it
 * auto-approves on the model's first proposal, which is the opposite of a
 * review gate.
 *
 * What *is* reachable is `AgentSession` itself: it carries the whole plan API
 * as public methods (`setPlanModeState`, `setPlanProposalHandler`,
 * `preparePlanForReview`, …). So omp-ui ships a generated omp extension,
 * written into the session's lineage dir and passed as `-e` at spawn — the same
 * per-lineage delivery ADR-0005 uses for the advisor overlay.
 *
 * The extension talks to omp-ui over two channels that already exist in the
 * rpc-ui protocol, so no new frame types are invented:
 * - `ui.setStatus(PLAN_STATUS_KEY, json)` publishes plan state (one-way).
 * - `ui.select("<PLAN_REVIEW_SENTINEL><json>", …)` requests approval and blocks
 *   the agent until the renderer answers.
 *
 * The wire constants live in ./plan, which the renderer imports directly.
 */

/** The extension file lives beside the transcript so it dies with the lineage. */
const EXTENSION_NAME = "omp-ui-plan.ts";

export function planExtensionPath(lineageDir: string): string {
  return path.join(lineageDir, EXTENSION_NAME);
}

/**
 * The extension source. A template rather than a checked-in file because it is
 * delivered per-lineage next to the transcript, and because the constants above
 * are the wire contract — they must not drift between the two sides.
 *
 * `AgentSession.prototype.prompt` is patched to capture the live session: omp's
 * `ExtensionContext` exposes `sessionManager` (a `ReadonlySessionManager` whose
 * 20 picked methods contain no plan API) but never the `AgentSession`. That is
 * unsupported surface, so the patch is wrapped: if it throws, or if the plan
 * methods are missing on the captured object, the extension publishes
 * `unavailable` and the UI disables the toggle rather than half-working.
 */
function extensionSource(): string {
  return `// Generated by omp-ui. Rewritten on every spawn; edits are not preserved.
import * as nodePath from "node:path";

const STATUS_KEY = ${JSON.stringify(PLAN_STATUS_KEY)};
const REVIEW_SENTINEL = ${JSON.stringify(PLAN_REVIEW_SENTINEL)};
const COMMAND = ${JSON.stringify(PLAN_COMMAND)};
const EXECUTE = ${JSON.stringify(PLAN_EXECUTE)};
const REFINE = ${JSON.stringify(PLAN_REFINE)};

/** The slice of omp's AgentSession this extension drives. */
interface PlanSession {
  isStreaming?: boolean;
  sessionManager: {
    getArtifactsDir?: () => string | null;
    appendModeChange: (mode: string, data?: { planFilePath: string }) => void;
  };
  getPlanModeState: () => { enabled?: boolean; planFilePath?: string } | undefined;
  setPlanModeState: (
    state: { enabled: boolean; planFilePath: string; workflow?: string } | undefined,
  ) => void;
  getPlanReferencePath: () => string;
  setPlanReferencePath: (path: string) => void;
  setPlanProposalHandler: (handler: ((title: string) => Promise<ToolResult>) | null) => void;
  preparePlanForReview: (title: string) => Promise<ToolResult>;
  setActiveToolsByName: (names: string[]) => Promise<void>;
  getEnabledToolNames: () => string[];
  hasBuiltInTool?: (name: string) => boolean;
  sendPlanModeContext?: (options: { deliverAs: "steer" }) => Promise<void>;
}

interface ToolResult {
  content: Array<{ type: "text"; text: string }>;
  details?: { planFilePath?: string; title?: string };
}

interface PlanUi {
  setStatus: (key: string, text: string | undefined) => void;
  select: (title: string, options: string[]) => Promise<string | undefined>;
  notify: (message: string, level?: "info" | "warning" | "error") => void;
}

interface PlanExtensionApi {
  pi?: { AgentSession?: { prototype?: Record<string, unknown> } };
  registerCommand: (
    name: string,
    options: {
      description?: string;
      handler: (args: string, ctx: { ui: PlanUi }) => Promise<void>;
    },
  ) => void;
}

export default function (pi: PlanExtensionApi) {
  let session: PlanSession | null = null;
  let unavailable: string | undefined;
  let approved = false;
  let previousTools: string[] | undefined;
  let ui: PlanUi | null = null;

  // Capture the live AgentSession. omp hands extensions no reference to it.
  try {
    const prototype = pi.pi?.AgentSession?.prototype;
    const originalPrompt = prototype?.prompt;
    if (!prototype || typeof originalPrompt !== "function") {
      unavailable = "AgentSession.prototype.prompt is not a function";
    } else {
      const call = originalPrompt as (this: PlanSession, ...a: unknown[]) => unknown;
      prototype.prompt = function (this: PlanSession, ...args: unknown[]): unknown {
        session = this;
        return call.apply(this, args);
      };
    }
  } catch (err) {
    unavailable = "could not hook AgentSession: " + String(err);
  }

  const REQUIRED = [
    "getPlanModeState",
    "setPlanModeState",
    "getPlanReferencePath",
    "setPlanReferencePath",
    "setPlanProposalHandler",
    "preparePlanForReview",
    "setActiveToolsByName",
    "getEnabledToolNames",
  ];

  /** Null when the session is usable; otherwise the reason it is not. */
  function unusable(): string | undefined {
    if (unavailable) return unavailable;
    const active = session;
    if (!active) return "no active omp session";
    const record = active as unknown as Record<string, unknown>;
    const missing = REQUIRED.filter(name => typeof record[name] !== "function");
    return missing.length > 0 ? "omp session is missing: " + missing.join(", ") : undefined;
  }

  /** \`local://x.md\` -> absolute path under the session's artifact sandbox. */
  function absolutePlanPath(planFilePath: string | null): string | null {
    if (!planFilePath) return null;
    const artifactsDir = session?.sessionManager?.getArtifactsDir?.();
    if (!artifactsDir) return null;
    const match = /^local:\\/{0,2}(.+)$/.exec(planFilePath);
    if (!match) return null;
    const relative = match[1];
    // Never let a crafted plan name escape the sandbox.
    const root = nodePath.resolve(artifactsDir, "local");
    const resolved = nodePath.resolve(root, relative);
    if (resolved !== root && !resolved.startsWith(root + nodePath.sep)) return null;
    return resolved;
  }

  function publish(): void {
    if (!ui) return;
    const state = session?.getPlanModeState?.();
    const planFilePath = state?.enabled ? (state.planFilePath ?? null) : null;
    const status = {
      enabled: state?.enabled === true,
      planFilePath,
      planAbsPath: absolutePlanPath(planFilePath),
      approved,
      unavailable: unusable(),
    };
    ui.setStatus(STATUS_KEY, JSON.stringify(status));
  }

  async function exitPlanMode(active: PlanSession): Promise<void> {
    active.setPlanProposalHandler(null);
    active.setPlanModeState(undefined);
    if (previousTools) await active.setActiveToolsByName(previousTools);
    previousTools = undefined;
    active.sessionManager.appendModeChange("none");
  }

  /**
   * Installed while plan mode is active; \`xd://propose\` dispatches the plan
   * title here. Blocks the agent on the renderer's answer, so a plan is never
   * executed without a decision.
   */
  async function onProposal(active: PlanSession, dialog: PlanUi, title: string): Promise<ToolResult> {
    // Validates the artifact and resolves the real slug the agent wrote to.
    const result = await active.preparePlanForReview(title);
    const details = result.details ?? {};
    const planFilePath = details.planFilePath ?? active.getPlanReferencePath();
    const request = {
      title: details.title ?? title,
      planFilePath,
      planAbsPath: absolutePlanPath(planFilePath),
    };

    let answer: string | undefined;
    try {
      answer = await dialog.select(REVIEW_SENTINEL + JSON.stringify(request), [EXECUTE, REFINE]);
    } catch {
      // A dropped dialog is a refusal, never a silent approval.
      answer = undefined;
    }

    if (answer !== EXECUTE) {
      // Rejection keeps plan mode active for another planning turn. Promote the
      // reviewed path into state so the next turn's plan-mode context targets
      // the plan just reviewed rather than a stale one.
      const state = active.getPlanModeState();
      if (state?.enabled && state.planFilePath !== planFilePath) {
        active.setPlanModeState({ enabled: true, planFilePath, workflow: "parallel" });
      }
      publish();
      return {
        content: [
          {
            type: "text",
            text:
              "Plan refinement requested. The user's revision notes may arrive as a " +
              "follow-up message; incorporate them, revise " +
              planFilePath +
              ", then write its title to xd://propose again when ready.",
          },
        ],
        details,
      };
    }

    // Accepted: pin the plan as the session's reference so whichever
    // implementation context the renderer chooses can read it, then leave plan
    // mode so write access returns. Crucially the agent does NOT implement
    // here — the renderer issues a separate implementation prompt (same
    // session, compacted, or a fresh session), so stop and wait for it.
    active.setPlanReferencePath(planFilePath);
    await exitPlanMode(active);
    approved = true;
    publish();
    return {
      content: [
        {
          type: "text",
          text:
            "Plan accepted and pinned as the reference at " +
            planFilePath +
            ". Plan mode exited. Do NOT start the implementation yet — a separate " +
            "implementation prompt will be issued. Stop and wait for it.",
        },
      ],
      details,
    };
  }

  async function enterPlanMode(active: PlanSession): Promise<void> {
    const planFilePath = active.getPlanReferencePath() || "local://PLAN.md";
    previousTools = active.getEnabledToolNames();
    // write stays active: plan mode's read-only guarantee is enforced by omp's
    // own plan-mode write guard, and the plan file itself needs writing.
    const tools = active.hasBuiltInTool?.("write")
      ? [...new Set([...previousTools, "write"])]
      : previousTools;
    await active.setActiveToolsByName(tools);
    active.setPlanModeState({ enabled: true, planFilePath, workflow: "parallel" });
    active.setPlanProposalHandler(title => {
      const dialog = ui;
      // Plan mode is only reachable through the command that sets \`ui\`.
      if (!dialog) throw new Error("omp-ui plan mode has no UI channel");
      return onProposal(active, dialog, title);
    });
    active.sessionManager.appendModeChange("plan", { planFilePath });
    // Mid-turn toggles need the plan rules delivered into the running turn.
    if (active.isStreaming && typeof active.sendPlanModeContext === "function") {
      await active.sendPlanModeContext({ deliverAs: "steer" });
    }
  }

  pi.registerCommand(COMMAND, {
    description: "omp-ui plan mode control",
    handler: async (args: string, ctx: { ui: PlanUi }) => {
      ui = ctx.ui;
      const reason = unusable();
      const active = session;
      if (reason || !active) {
        publish();
        ctx.ui.notify("Plan mode unavailable: " + (reason ?? "no active omp session"), "error");
        return;
      }
      const want = args.trim().toLowerCase();
      const on = active.getPlanModeState()?.enabled === true;
      const next = want === "on" ? true : want === "off" ? false : !on;
      if (next === on) {
        publish();
        return;
      }
      if (next) await enterPlanMode(active);
      else await exitPlanMode(active);
      publish();
    },
  });
}
`;
}

/**
 * Writes the plan extension into the lineage dir and returns its path, to be
 * passed to omp as `-e`. Rewritten on every spawn so a stale copy from an older
 * omp-ui build can never outvote the current wire contract.
 */
export function writePlanExtension(lineageDir: string): string {
  const file = planExtensionPath(lineageDir);
  fs.mkdirSync(lineageDir, { recursive: true });
  fs.writeFileSync(file, extensionSource(), "utf8");
  return file;
}
