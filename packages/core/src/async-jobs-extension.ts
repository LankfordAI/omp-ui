import * as path from "node:path";
import {
  ASYNC_JOB_STATUSES,
  ASYNC_JOBS_COMMAND,
  ASYNC_JOBS_COMMAND_CHAR_LIMIT,
  ASYNC_JOBS_KILL_ARG,
  ASYNC_JOBS_LABEL_CHAR_LIMIT,
  ASYNC_JOBS_OUTPUT_TAIL_CHARS,
  ASYNC_JOBS_POLL_MS,
  ASYNC_JOBS_RECENT_LIMIT,
  ASYNC_JOBS_SHORT_TAIL_CHARS,
  ASYNC_JOBS_STATUS_BYTE_LIMIT,
  ASYNC_JOBS_STATUS_KEY,
} from "./async-jobs";
import { writeLineageArtifact } from "./lineage-artifact";
import {
  generatedAsRecordSource,
  generatedPollTimerSource,
  generatedRootBindingSource,
  generatedShutdownCleanupSource,
  generatedUtf8LengthSource,
} from "./generated-extension-source";

/**
 * omp's rpc surface carries no background-job state (issue #835): no rpc
 * frame lists jobs and `get_state` only reports `hasPendingAsyncWork`. The
 * public methods on the live `AgentSession` do —
 * `getAsyncJobSnapshot({ recentLimit })`, `inspectAsyncJob(id)`, and
 * `cancelAsyncJob(id)` are what omp's own `/jobs` and the TUI jobs sheet use.
 * This generated extension patches `AgentSession.prototype.prompt`, binds the
 * first prompt as the root session, and publishes a digest-gated snapshot of
 * the root's async job manager over `ui.setStatus`.
 *
 * Kill rides the same hidden command mid-turn: omp resolves a registered
 * extension command inside `AgentSession.prompt` before its streaming check,
 * so `/omp-ui-async-jobs kill <json>` executes while the agent is busy (the
 * rpc serial chain releases a prompt at admission, not at turn end — verified
 * on omp/18.8.9). Every request carries the bridge's own `processKey` and the
 * target job's `startTime`, because omp reuses `bg_N` ids after eviction.
 *
 * Degradation is by method presence, never by version string: a missing API
 * publishes `available: false` with the reason, or clears
 * `canInspect`/`canCancel` so the pane renders no affordance the build cannot
 * serve. Daemon-supervised `bash name=…` services never enter the job
 * manager and stay outside this bridge (ADR-0054).
 */

/** The extension file lives beside the transcript so it dies with the lineage. */
const EXTENSION_NAME = "omp-ui-async-jobs.ts";

export function asyncJobsExtensionPath(lineageDir: string): string {
  return path.join(lineageDir, EXTENSION_NAME);
}

/**
 * The generated source imports nothing; the wire constants are interpolated
 * from async-jobs.ts so the publishing side can never drift from the parser
 * the renderer shares.
 */
function extensionSource(): string {
  return `// Generated by omp-ui. Rewritten on every spawn; edits are not preserved.
const STATUS_KEY = ${JSON.stringify(ASYNC_JOBS_STATUS_KEY)};
const COMMAND = ${JSON.stringify(ASYNC_JOBS_COMMAND)};
const KILL_ARG = ${JSON.stringify(ASYNC_JOBS_KILL_ARG)};
const STATUSES: readonly string[] = ${JSON.stringify(ASYNC_JOB_STATUSES)};
const BYTE_LIMIT = ${ASYNC_JOBS_STATUS_BYTE_LIMIT};
const POLL_MS = ${ASYNC_JOBS_POLL_MS};
const RECENT_LIMIT = ${ASYNC_JOBS_RECENT_LIMIT};
const TAIL_CHARS = ${ASYNC_JOBS_OUTPUT_TAIL_CHARS};
const SHORT_TAIL_CHARS = ${ASYNC_JOBS_SHORT_TAIL_CHARS};
const LABEL_LIMIT = ${ASYNC_JOBS_LABEL_CHAR_LIMIT};
const COMMAND_LIMIT = ${ASYNC_JOBS_COMMAND_CHAR_LIMIT};
const ANSI = /\\u001b\\[[0-?]*[ -\\/]*[@-~]/g;
const CONTROL = /[\\u0000-\\u0008\\u000b-\\u001f\\u007f-\\u009f]/g;

${generatedAsRecordSource()}

${generatedUtf8LengthSource()}

${generatedPollTimerSource()}

interface StatusUi {
  setStatus: (key: string, text: string | undefined) => void;
}

interface JobsSession {
  getAsyncJobSnapshot?: unknown;
  inspectAsyncJob?: unknown;
  cancelAsyncJob?: unknown;
}

interface ExtensionApi {
  pi?: { AgentSession?: { prototype?: Record<string, unknown> } };
  registerCommand: (
    name: string,
    options: { description?: string; handler: (args: string, ctx: { ui: StatusUi }) => Promise<void> },
  ) => void;
}

/** One job as read, with its full cleaned output; shaped per byte-budget rung. */
interface CollectedJob {
  id: string;
  type: string;
  status: string;
  label: string;
  command: string | null;
  cwd: string | null;
  startTime: number;
  endTime: number | null;
  agentId: string | null;
  pids: number[];
  exitCode: number | null;
  output: string;
}

interface Collected {
  available: boolean;
  unavailable: string | null;
  canInspect: boolean;
  canCancel: boolean;
  running: CollectedJob[];
  recent: CollectedJob[];
}

interface KillRequest {
  requestId: string;
  processKey: string;
  jobId: string | null;
  startTime: number | null;
}

interface KillResult {
  requestId: string;
  ok: boolean;
  cancelled: string[];
  text: string;
}

function str(value: unknown): string {
  return typeof value === "string" ? value : "";
}

function finite(value: unknown): number | null {
  return typeof value === "number" && Number.isFinite(value) ? value : null;
}

/** Output reaches JSON as display text: escapes go, \\n and \\t stay. */
function clean(value: string): string {
  return value.replace(ANSI, "").replace(CONTROL, "");
}

function clip(value: string, limit: number): string {
  return value.length > limit ? value.slice(0, limit - 1) + "\\u2026" : value;
}

export default function (pi: ExtensionApi) {
  const processKey = "omp-ui-" + Date.now().toString(36) + "-" + Math.random().toString(36).slice(2);
  let rootSession: JobsSession | null = null;
  let ui: StatusUi | null = null;
  let revision = 0;
  let lastDigest = "";
  /** Set only when the prompt hook could not be installed; outranks every read. */
  let hookBroken: string | null = null;
  let pollTimer: PollTimer | null = null;

  ${generatedShutdownCleanupSource("JobsSession")}

  ${generatedRootBindingSource("JobsSession", "bindShutdown(candidate);")}

  function teardown(): void {
    if (pollTimer === null) return;
    try {
      clearInterval(pollTimer as unknown as number);
    } catch {
      /* a runtime that refuses clearInterval still loses its handle */
    }
    pollTimer = null;
  }

  function startPoll(): void {
    if (pollTimer !== null) return;
    const timer = setInterval(() => {
      try {
        publish(false, null);
      } catch {
        /* a poll failure must never surface in the session */
      }
    }, POLL_MS);
    pollTimer = timer as unknown as PollTimer;
    try {
      pollTimer.unref?.();
    } catch {
      /* an unref-less runtime keeps the interval as-is */
    }
  }

  function unavailable(reason: string): Collected {
    return { available: false, unavailable: reason, canInspect: false, canCancel: false, running: [], recent: [] };
  }

  function collectJob(raw: unknown, root: JobsSession, canInspect: boolean): CollectedJob | null {
    const job = asRecord(raw);
    if (job === null) return null;
    const id = str(job.id);
    const type = str(job.type);
    const status = str(job.status);
    const startTime = finite(job.startTime);
    if (id === "" || type === "" || STATUSES.indexOf(status) < 0 || startTime === null) return null;
    let detail: Record<string, unknown> | null = null;
    if (canInspect) {
      try {
        detail = asRecord((root.inspectAsyncJob as (jobId: string) => unknown).call(root, id));
      } catch {
        detail = null;
      }
    }
    const pick = (key: string): unknown => (detail === null ? undefined : detail[key]);
    const pids: number[] = [];
    const rawPids = pick("pids");
    if (Array.isArray(rawPids)) {
      for (const pid of rawPids) if (typeof pid === "number" && Number.isInteger(pid)) pids.push(pid);
    }
    const command = clean(str(pick("command")) || str(job.command));
    const cwd = str(pick("cwd"));
    const agentId = str(job.agentId);
    return {
      id,
      type,
      status,
      startTime,
      pids,
      label: clip(clean(str(job.label)), LABEL_LIMIT),
      command: command === "" ? null : clip(command, COMMAND_LIMIT),
      cwd: cwd === "" ? null : cwd,
      endTime: finite(job.endTime),
      agentId: agentId === "" ? null : agentId,
      exitCode: finite(pick("exitCode")),
      output: clean(str(pick("output"))),
    };
  }

  function collect(): Collected {
    if (hookBroken !== null) return unavailable(hookBroken);
    const root = rootSession;
    if (root === null) return unavailable("no omp session has prompted yet");
    if (typeof root.getAsyncJobSnapshot !== "function") {
      return unavailable("this omp build has no background-job API");
    }
    const canInspect = typeof root.inspectAsyncJob === "function";
    const canCancel = typeof root.cancelAsyncJob === "function";
    let raw: unknown;
    try {
      raw = (root.getAsyncJobSnapshot as (options: { recentLimit: number }) => unknown).call(root, {
        recentLimit: RECENT_LIMIT,
      });
    } catch (err) {
      return unavailable("getAsyncJobSnapshot failed: " + String(err));
    }
    if (raw === null || raw === undefined) return unavailable("background jobs are unavailable in this session");
    const record = asRecord(raw);
    if (record === null) return unavailable("getAsyncJobSnapshot returned no object");
    const read = (list: unknown): CollectedJob[] => {
      const jobs: CollectedJob[] = [];
      if (!Array.isArray(list)) return jobs;
      for (const item of list) {
        const job = collectJob(item, root, canInspect);
        if (job !== null) jobs.push(job);
      }
      return jobs;
    };
    return { available: true, unavailable: null, canInspect, canCancel, running: read(record.running), recent: read(record.recent) };
  }

  function shape(job: CollectedJob, tailChars: number): Record<string, unknown> {
    const truncated = job.output.length > tailChars;
    return {
      id: job.id,
      type: job.type,
      status: job.status,
      label: job.label,
      command: job.command,
      cwd: job.cwd,
      startTime: job.startTime,
      endTime: job.endTime,
      agentId: job.agentId,
      pids: job.pids,
      exitCode: job.exitCode,
      outputTail: truncated ? job.output.slice(job.output.length - tailChars) : job.output,
      outputTruncated: truncated,
    };
  }

  function body(c: Collected, tailChars: number): Record<string, unknown> {
    return {
      available: c.available,
      unavailable: c.unavailable,
      canInspect: c.canInspect,
      canCancel: c.canCancel,
      running: c.running.map((job) => shape(job, tailChars)),
      recent: c.recent.map((job) => shape(job, tailChars)),
    };
  }

  function publish(force: boolean, result: KillResult | null): void {
    if (ui === null) return;
    const collected = collect();
    const full = body(collected, TAIL_CHARS);
    const digest = JSON.stringify(full);
    if (!force && digest === lastDigest) return;
    const envelope = (b: Record<string, unknown>): string =>
      JSON.stringify(Object.assign({ version: 1, processKey, revision: revision + 1 }, b, { result }));
    // An impossible payload degrades rung by rung, never into half a job.
    let json = envelope(full);
    if (utf8Length(json) > BYTE_LIMIT) json = envelope(body(collected, SHORT_TAIL_CHARS));
    if (utf8Length(json) > BYTE_LIMIT) json = envelope(body(collected, 0));
    if (utf8Length(json) > BYTE_LIMIT) {
      json = envelope(body(unavailable("background job list exceeded " + BYTE_LIMIT + " bytes"), 0));
    }
    revision += 1;
    lastDigest = digest;
    ui.setStatus(STATUS_KEY, json);
  }

  function parseKill(raw: string): KillRequest | null {
    let value: unknown;
    try {
      value = JSON.parse(raw);
    } catch {
      return null;
    }
    const r = asRecord(value);
    if (r === null) return null;
    const requestId = r.requestId;
    const key = r.processKey;
    const jobId = r.jobId;
    if (typeof requestId !== "string" || requestId === "" || requestId.length > 128) return null;
    if (typeof key !== "string" || key === "") return null;
    if (jobId === null) return r.startTime === null ? { requestId, processKey: key, jobId: null, startTime: null } : null;
    if (typeof jobId !== "string" || jobId === "" || jobId.length > 256) return null;
    const startTime = finite(r.startTime);
    return startTime === null ? null : { requestId, processKey: key, jobId, startTime };
  }

  function kill(request: KillRequest): KillResult {
    const fail = (text: string): KillResult => ({ requestId: request.requestId, ok: false, cancelled: [], text });
    if (request.processKey !== processKey) {
      return fail("This job list came from an earlier omp process; refresh it and try again.");
    }
    const current = collect();
    const root = rootSession;
    if (!current.available || root === null) return fail(current.unavailable ?? "background jobs are unavailable");
    if (!current.canCancel) return fail("this omp build cannot cancel background jobs (needs omp 18.4.9 or later)");
    const cancel = (id: string): boolean =>
      (root.cancelAsyncJob as (jobId: string) => unknown).call(root, id) === true;
    if (request.jobId === null) {
      const cancelled = current.running.filter((job) => cancel(job.id)).map((job) => job.id);
      return {
        requestId: request.requestId,
        ok: true,
        cancelled,
        text: cancelled.length === 0
          ? "No running background jobs to cancel."
          : "Cancelled " + cancelled.length + " background job" + (cancelled.length === 1 ? "" : "s") + ".",
      };
    }
    const jobId = request.jobId;
    const target = current.running.find((job) => job.id === jobId);
    if (target === undefined) return fail('No running background job with id "' + jobId + '".');
    // omp reuses bg_N after eviction: a stale row must never cancel its successor.
    if (target.startTime !== request.startTime) {
      return fail("Background job " + jobId + " already finished; a newer job now uses that id.");
    }
    return cancel(jobId)
      ? { requestId: request.requestId, ok: true, cancelled: [jobId], text: "Cancelled background job " + jobId + "." }
      : fail("Could not cancel background job " + jobId + ".");
  }

  try {
    const prototype = pi.pi?.AgentSession?.prototype;
    const originalPrompt = prototype?.prompt;
    if (prototype === undefined || typeof originalPrompt !== "function") {
      hookBroken = "AgentSession.prototype.prompt is not a function";
    } else {
      const call = originalPrompt as (this: JobsSession, ...args: unknown[]) => unknown;
      prototype.prompt = function (this: JobsSession, ...args: unknown[]): unknown {
        captureRoot(this);
        return call.apply(this, args);
      };
    }
  } catch (err) {
    hookBroken = "could not hook AgentSession: " + String(err);
  }

  pi.registerCommand(COMMAND, {
    description: "omp-ui background jobs bridge",
    handler: async (args: string, ctx: { ui: StatusUi }) => {
      ui = ctx.ui;
      const text = typeof args === "string" ? args.trim() : "";
      if (text === "") {
        startPoll();
        publish(true, null);
        return;
      }
      if (!text.startsWith(KILL_ARG + " ")) throw new Error("omp-ui-async-jobs: unsupported command args");
      const request = parseKill(text.slice(KILL_ARG.length + 1));
      if (request === null) throw new Error("omp-ui-async-jobs: malformed kill request");
      startPoll();
      let result: KillResult;
      try {
        result = kill(request);
      } catch (err) {
        result = { requestId: request.requestId, ok: false, cancelled: [], text: "cancel failed: " + String(err) };
      }
      publish(true, result);
    },
  });
}
`;
}

/**
 * Writes the background-jobs bridge into the lineage dir and returns its
 * path, to be passed to omp as `-e`. Rewritten on every spawn so a stale copy
 * from an older omp-ui build can never outvote the current wire contract.
 */
export function writeAsyncJobsExtension(lineageDir: string): string {
  return writeLineageArtifact(lineageDir, asyncJobsExtensionPath(lineageDir), extensionSource());
}
