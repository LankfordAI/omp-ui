import { generatedRootBindingSource } from "./generated-extension-source";

/**
 * Generator for the hidden-context bridges (ADR-0060): one hidden
 * `display: false` custom message per armed text, deduplicated by walking the
 * current branch back to the last compaction/reset boundary. Ask chats (#895)
 * re-run delivery on session events; the restart carryover (#824, #896)
 * delivers once per arm.
 */

export type HiddenContextResendEvent = "session_compact" | "session_branch" | "session_switch";

export interface HiddenContextBridgeSpec {
  /** Slash command the spawner pushes through initialCommands. */
  command: string;
  /** customType of the hidden message; the dedupe walk matches on it alone. */
  customType: string;
  /** Inclusive UTF-16 ceiling on the `set` payload's text. */
  textMax: number;
  /** Command description and prefix of every notify, e.g. "omp-ui ask context". */
  label: string;
  /** omp session events after which delivery re-runs (the dedupe walk decides). */
  resendOn: readonly HiddenContextResendEvent[];
}

/** The hidden slash command a spawner pushes through initialCommands. */
export function hiddenContextArmMessage(command: string, text: string): string {
  return `/${command} set ${JSON.stringify({ text })}`;
}

/**
 * The generated source imports nothing; the command name, custom type, length
 * cap, label, and resend events are interpolated from the spec so the two
 * sides of the channel can never drift.
 */
export function hiddenContextExtensionSource(spec: HiddenContextBridgeSpec): string {
  return `// Generated by omp-ui. Rewritten on every spawn; edits are not preserved.

const COMMAND = ${JSON.stringify(spec.command)};
const CUSTOM_TYPE = ${JSON.stringify(spec.customType)};
const TEXT_MAX = ${spec.textMax};
const LABEL = ${JSON.stringify(spec.label)};
const RESEND_ON: readonly string[] = ${JSON.stringify(spec.resendOn)};

/** One entry of omp's session tree, as far as the dedupe walk reads it. */
interface HiddenContextBranchEntry {
  type?: unknown;
  customType?: unknown;
}

/** The slice of omp's AgentSession this extension drives. */
interface HiddenContextSession {
  isStreaming?: boolean;
  sessionManager?: { getBranch?: () => unknown };
  sendCustomMessage?: (
    msg: { customType: string; content: string; display: boolean; attribution: string },
    opts: { deliverAs: "steer" | "nextTurn"; triggerTurn: boolean },
  ) => Promise<unknown>;
}

interface HiddenContextUi {
  notify: (message: string, level?: "info" | "warning" | "error") => void;
}

interface HiddenContextExtensionApi {
  pi?: { AgentSession?: { prototype?: Record<string, unknown> } };
  registerCommand: (
    name: string,
    options: {
      description?: string;
      handler: (args: string, ctx: { ui: HiddenContextUi }) => Promise<void>;
    },
  ) => void;
  on?: (event: string, handler: (...args: unknown[]) => void) => void;
}

export default function (pi: HiddenContextExtensionApi) {
  // The first prompting AgentSession. omp dispatches slash commands through
  // prompt, so the arming command itself binds the root; no later prompt —
  // descendant or not — may retarget it (ADR-0008 discipline).
  let rootSession: HiddenContextSession | null = null;
  /** The pinned text the spawner armed; null until the first set. */
  let text: string | null = null;
  let warnedUnavailable = false;
  let ui: HiddenContextUi | null = null;
  ${generatedRootBindingSource("HiddenContextSession")}

  try {
    const prototype = pi.pi?.AgentSession?.prototype;
    const originalPrompt = prototype?.prompt;
    if (prototype && typeof originalPrompt === "function") {
      const call = originalPrompt as (this: HiddenContextSession, ...a: unknown[]) => unknown;
      prototype.prompt = function (this: HiddenContextSession, ...args: unknown[]): unknown {
        captureRoot(this);
        return call.apply(this, args);
      };
    }
  } catch {
    // Without the hook there is no root to deliver to; deliver() warns once.
  }

  /**
   * True when the current branch, walked from its leaf back to the last
   * compaction or reset boundary, already holds the pinned message. Matches
   * the customType alone: the text is a snapshot, so a re-rendered copy must
   * never stack beside the original. No getBranch reads as not pinned.
   */
  function alreadyPinned(root: HiddenContextSession): boolean {
    let branch: unknown;
    try {
      const getBranch = root.sessionManager?.getBranch;
      if (typeof getBranch !== "function") return false;
      branch = getBranch.call(root.sessionManager);
    } catch {
      return false;
    }
    if (!Array.isArray(branch)) return false;
    for (let i = branch.length - 1; i >= 0; i--) {
      const entry = branch[i] as HiddenContextBranchEntry | null;
      if (entry === null || typeof entry !== "object") continue;
      if (entry.type === "compaction" || entry.type === "reset_boundary") return false;
      if (entry.type === "custom_message" && entry.customType === CUSTOM_TYPE) return true;
    }
    return false;
  }

  /** Sends the hidden pinned text to the root unless the branch already holds it. */
  async function deliver(): Promise<void> {
    const active = rootSession;
    const target = text;
    if (target === null) return;
    if (!active || typeof active.sendCustomMessage !== "function") {
      if (!warnedUnavailable) {
        warnedUnavailable = true;
        ui?.notify(LABEL + ": this omp cannot carry the pinned context to the agent", "warning");
      }
      return;
    }
    if (alreadyPinned(active)) return;
    try {
      await active.sendCustomMessage(
        {
          customType: CUSTOM_TYPE,
          content: target,
          display: false,
          attribution: "agent",
        },
        { deliverAs: active.isStreaming ? "steer" : "nextTurn", triggerTurn: false },
      );
    } catch {
      // Retried by the next set or session event.
    }
  }

  /** Strict parse of the set payload: exactly { text } holding 1 to TEXT_MAX units. */
  function parseSetArgs(args: string): string | null {
    let parsed: unknown;
    try {
      parsed = JSON.parse(args);
    } catch {
      return null;
    }
    if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) return null;
    if (!("text" in parsed) || Object.keys(parsed).length !== 1) return null;
    const value: unknown = parsed.text;
    if (typeof value !== "string" || value.length < 1 || value.length > TEXT_MAX) return null;
    return value;
  }

  // Two quick sets must not interleave their deliveries.
  let chain: Promise<void> = Promise.resolve();
  function serialize(work: () => Promise<void>): Promise<void> {
    const next = chain.then(work, work);
    chain = next.then(
      () => undefined,
      () => undefined,
    );
    return next;
  }

  pi.registerCommand(COMMAND, {
    description: LABEL,
    handler: (args: string, ctx: { ui: HiddenContextUi }) =>
      serialize(async () => {
        ui = ctx.ui;
        const trimmed = args.trim();
        if (!trimmed.startsWith("set ")) {
          ctx.ui.notify(LABEL + ": unknown command", "warning");
          return;
        }
        const next = parseSetArgs(trimmed.slice(4));
        if (next === null) {
          ctx.ui.notify(LABEL + ": malformed context", "warning");
          return;
        }
        text = next;
        await deliver();
      }),
  });

  // Each spec's resend events rebuild the context the hidden message lived in; the dedupe walk alone decides whether to send again.
  if (typeof pi.on === "function") {
    for (const eventName of RESEND_ON) {
      pi.on(eventName, () => {
        if (text !== null) void serialize(deliver);
      });
    }
  }
}
`;
}
