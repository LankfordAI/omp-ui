import * as path from "node:path";
import { generatedRootBindingSource } from "./generated-extension-source";
import { writeLineageArtifact } from "./lineage-artifact";
import {
  FLEET_WAKE_COMMAND,
  FLEET_WAKE_CUSTOM_TYPE,
  FLEET_WAKE_STATUS_KEY,
  FLEET_WAKE_TEXT_MAX,
} from "./fleet-wake";

/**
 * Generator for the fleet-wake bridge (issue #957, ADR-0069): delivers one
 * visible Fleet result or Fleet notice per armed wakeId into the root session
 * and starts a turn there. Deduplicated against the whole branch (a crash
 * after omp persisted the message re-arms it; the bridge acknowledges over
 * setStatus instead of sending again) and against the ids this process
 * already handed to omp.
 */

const EXTENSION_NAME = "omp-ui-fleet-wake.ts";

export function fleetWakeExtensionPath(lineageDir: string): string {
  return path.join(lineageDir, EXTENSION_NAME);
}

/** The generated source imports nothing; its wire constants come from fleet-wake.ts. */
export function fleetWakeExtensionSource(): string {
  return `// Generated by omp-ui. Rewritten on every spawn; edits are not preserved.

const COMMAND = ${JSON.stringify(FLEET_WAKE_COMMAND)};
const CUSTOM_TYPE = ${JSON.stringify(FLEET_WAKE_CUSTOM_TYPE)};
const STATUS_KEY = ${JSON.stringify(FLEET_WAKE_STATUS_KEY)};
const TEXT_MAX = ${FLEET_WAKE_TEXT_MAX};
const CARD_JSON_MAX = 4096;
const WAKE_ID = /^[A-Za-z0-9._-]{1,160}$/;
const LABEL = "omp-ui fleet wake";

/** One entry of omp's session tree, as far as the dedupe walk reads it. */
interface FleetWakeBranchEntry {
  type?: unknown;
  customType?: unknown;
  details?: unknown;
}

interface FleetWakeCard {
  wakeId: string;
  [key: string]: unknown;
}

/** The slice of omp's AgentSession this extension drives. */
interface FleetWakeSession {
  isStreaming?: boolean;
  sessionManager?: { getBranch?: () => unknown };
  sendCustomMessage?: (
    msg: { customType: string; content: string; display: boolean; attribution: string; details: unknown },
    opts: { deliverAs: "followUp" | "nextTurn"; triggerTurn: boolean },
  ) => Promise<unknown>;
}

interface FleetWakeUi {
  notify: (message: string, level?: "info" | "warning" | "error") => void;
  setStatus: (key: string, text: string | undefined) => void;
}

interface FleetWakeExtensionApi {
  pi?: { AgentSession?: { prototype?: Record<string, unknown> } };
  registerCommand: (
    name: string,
    options: {
      description?: string;
      handler: (args: string, ctx: { ui: FleetWakeUi }) => Promise<void>;
    },
  ) => void;
}

export default function (pi: FleetWakeExtensionApi) {
  // The first prompting AgentSession; the arming command itself binds it
  // (ADR-0008 discipline: no later prompt may retarget it).
  let rootSession: FleetWakeSession | null = null;
  let warnedUnavailable = false;
  /** Wake ids handed to sendCustomMessage in this process; their own message_end settles them. */
  const handed = new Set<string>();
  ${generatedRootBindingSource("FleetWakeSession")}

  try {
    const prototype = pi.pi?.AgentSession?.prototype;
    const originalPrompt = prototype?.prompt;
    if (prototype && typeof originalPrompt === "function") {
      const call = originalPrompt as (this: FleetWakeSession, ...a: unknown[]) => unknown;
      prototype.prompt = function (this: FleetWakeSession, ...args: unknown[]): unknown {
        captureRoot(this);
        return call.apply(this, args);
      };
    }
  } catch {
    // Without the hook there is no root to deliver to; the handler warns once.
  }

  /** True when any entry of the whole branch already holds this wake; compaction does not end the walk. */
  function alreadyDelivered(root: FleetWakeSession, wakeId: string): boolean {
    let branch: unknown;
    try {
      const getBranch = root.sessionManager?.getBranch;
      if (typeof getBranch !== "function") return false;
      branch = getBranch.call(root.sessionManager);
    } catch {
      return false;
    }
    if (!Array.isArray(branch)) return false;
    for (const raw of branch) {
      const entry = raw as FleetWakeBranchEntry | null;
      if (entry === null || typeof entry !== "object") continue;
      if (entry.type !== "custom_message" || entry.customType !== CUSTOM_TYPE) continue;
      const details = entry.details as { wakeId?: unknown } | null | undefined;
      if (details !== null && typeof details === "object" && details.wakeId === wakeId) return true;
    }
    return false;
  }

  /** Strict parse of the deliver payload: exactly { text, card }. */
  function parseDeliverArgs(args: string): { text: string; card: FleetWakeCard } | null {
    let parsed: unknown;
    try {
      parsed = JSON.parse(args);
    } catch {
      return null;
    }
    if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) return null;
    if (!("text" in parsed) || !("card" in parsed) || Object.keys(parsed).length !== 2) return null;
    const text: unknown = parsed.text;
    const card: unknown = parsed.card;
    if (typeof text !== "string" || text.length < 1 || text.length > TEXT_MAX) return null;
    if (typeof card !== "object" || card === null || Array.isArray(card)) return null;
    const wakeId: unknown = (card as { wakeId?: unknown }).wakeId;
    if (typeof wakeId !== "string" || !WAKE_ID.test(wakeId)) return null;
    if (JSON.stringify(card).length > CARD_JSON_MAX) return null;
    return { text, card: card as FleetWakeCard };
  }

  // Idle arms each run a turn; one after another, never interleaved.
  let chain: Promise<void> = Promise.resolve();
  function serialize(work: () => Promise<void>): Promise<void> {
    const next = chain.then(work, work);
    chain = next.then(
      () => undefined,
      () => undefined,
    );
    return next;
  }

  pi.registerCommand(COMMAND, {
    description: LABEL,
    handler: (args: string, ctx: { ui: FleetWakeUi }) =>
      serialize(async () => {
        const trimmed = args.trim();
        if (!trimmed.startsWith("deliver ")) {
          ctx.ui.notify(LABEL + ": unknown command", "warning");
          return;
        }
        const payload = parseDeliverArgs(trimmed.slice("deliver ".length));
        if (payload === null) {
          ctx.ui.notify(LABEL + ": malformed message", "warning");
          return;
        }
        const root = rootSession;
        if (!root || typeof root.sendCustomMessage !== "function") {
          if (!warnedUnavailable) {
            warnedUnavailable = true;
            ctx.ui.notify(LABEL + ": this omp cannot deliver fleet results", "warning");
          }
          return;
        }
        const wakeId = payload.card.wakeId;
        if (handed.has(wakeId)) return;
        if (alreadyDelivered(root, wakeId)) {
          ctx.ui.setStatus(STATUS_KEY, JSON.stringify({ wakeId }));
          return;
        }
        handed.add(wakeId);
        try {
          await root.sendCustomMessage(
            { customType: CUSTOM_TYPE, content: payload.text, display: true, attribution: "agent", details: payload.card },
            { deliverAs: root.isStreaming ? "followUp" : "nextTurn", triggerTurn: true },
          );
        } catch {
          // main re-arms on the next process.
          handed.delete(wakeId);
        }
      }),
  });
}
`;
}

/**
 * Writes the fleet-wake extension into the lineage dir and returns its path,
 * to be passed to omp as \`-e\`. Rewritten on every spawn.
 */
export function writeFleetWakeExtension(lineageDir: string): string {
  return writeLineageArtifact(lineageDir, fleetWakeExtensionPath(lineageDir), fleetWakeExtensionSource());
}
