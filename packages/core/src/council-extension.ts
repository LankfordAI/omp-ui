/**
 * The generated `/council` bridge (ADR-0088, issue #1049). It ships as an
 * extension package directory passed to omp as `-e <dir>`: `package.json`
 * declares the bridge entry, and `agents/omp-ui-council.md` is the dedicated
 * task agent every member runs as — omp discovers `agents/*.md` only for
 * explicit directory roots, never beside a file entrypoint.
 *
 * Both surfaces — the slash command and the model-callable tool — use the
 * same council state captured at spawn. Ask mode hands each member the
 * request; review mode resolves the diff target once with async git/gh probes.
 * The launch goes to the session model with `pi.sendMessage` (deliverAs
 * nextTurn, triggerTurn true): the binary exposes no callTool on any extension
 * ctx, so the model makes the single batch `task` call. Each item names the
 * council agent and its member's model; the council overlay grants exactly
 * those models. The batch JSON rides inert-fenced so nothing in the repo's
 * refs or the council can arm magic keywords on the way through.
 */

