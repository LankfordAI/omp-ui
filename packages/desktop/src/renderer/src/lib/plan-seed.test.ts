import { describe, expect, it } from "vitest";
import { planSeedText } from "./plan-seed";

describe("planSeedText", () => {
  it("passes a markdown plan through byte-identical", () => {
    // Markdown plans are already prompt text — touching them at all would risk
    // corrupting fenced blocks that carry the spec's code.
    const md = "# Plan\n\nStep one.\n\n```ts\nconst x: number = 1;\n```\n";
    expect(planSeedText(md)).toBe(md);
  });

  it("returns null when there is no plan text", () => {
    // No plan file read yet (or an unreadable one) — the caller falls back.
    expect(planSeedText(null)).toBeNull();
  });

  it("strips style, script, and comments from an html plan but keeps its markup", () => {
    // An html plan's presentation layer is pure token cost in a prompt; its
    // headings and tables are the structure the implementer reads.
    const html = [
      "<!doctype html>",
      "<html>",
      "<head><style>h1 { color: rebeccapurple; }</style></head>",
      "<body>",
      "<!-- generated by the planner -->",
      "<h1>Ship the auth rewrite</h1>",
      "<table><tr><td>step one</td></tr></table>",
      '<script>document.title = "hydrated";</script>',
      "</body>",
      "</html>",
    ].join("\n");
    const seed = planSeedText(html);
    expect(seed).toContain("<h1>Ship the auth rewrite</h1>");
    expect(seed).toContain("<table><tr><td>step one</td></tr></table>");
    expect(seed).not.toContain("rebeccapurple");
    expect(seed).not.toContain("hydrated");
    expect(seed).not.toContain("generated by the planner");
  });

  it("returns null for a document that was nothing but styling", () => {
    // A stylesheet with no body is worse than no seed at all: the fallback
    // prompt at least does not claim to carry a spec.
    const shell = [
      "<!doctype html>",
      "<html>",
      "<head><style>body { margin: 0; }</style></head>",
      "<body></body>",
      "</html>",
    ].join("\n");
    expect(planSeedText(shell)).toBeNull();
  });
});
